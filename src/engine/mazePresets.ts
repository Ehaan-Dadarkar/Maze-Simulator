function fromRows(rows: string[], start: Cell, end: Cell): Maze {
  const m = makeMaze(rows.length);
  m.start = { ...start };
  m.end = { ...end };
  rows.forEach((row, y) => [...row].forEach((v, x) => {
    if (v === "#") m.roads.add(key({ x, y }));
  }));
  m.roads.add(key(start));
  return m;
}

